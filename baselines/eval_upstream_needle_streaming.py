"""Streaming-mode Needle-in-a-haystack eval for SnapKV / H2O / PyramidKV.

Same AstroNet-S1 streaming protocol as the SQuAD / LongBench streaming
runners, applied to the synthetic Needle benchmark generated by
``baselines.eval_needle.generate_haystack``.

Usage::

    python baselines/eval_upstream_needle_streaming.py \\
        --model_path ./models/qwen2.5-7b --method snapkv --k 300 \\
        --n_windows_list 5 10 20 --n_trials 20 \\
        --save_path logs/results/upstream_needle_snapkv_qwen7b_streaming.json
"""
from __future__ import annotations
import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from baselines.eval_upstream_baselines_streaming import (
    _family_from_path, load_backbone, _inject_layers,
    _question_q_at_layers, _score_method, _select_indices, _select_kv,
)


DEPTH_KEYS = ['start', '25%', '50%', '75%', 'end']


def depth_positions(n_windows: int):
    if n_windows < 5:
        return list(range(n_windows))
    return [
        0,
        max(1, n_windows // 4),
        max(2, n_windows // 2),
        max(3, (3 * n_windows) // 4),
        n_windows - 1,
    ]


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--model_path', required=True)
    p.add_argument('--method', required=True,
                   choices=['snapkv', 'h2o', 'pyramidkv'])
    p.add_argument('--k', type=int, default=300)
    p.add_argument('--n_windows_list', nargs='+', type=int, default=[5, 10, 20])
    p.add_argument('--n_trials', type=int, default=20)
    p.add_argument('--seed_offset', type=int, default=0)
    p.add_argument('--multi_gpu', action='store_true')
    p.add_argument('--save_path', required=True)
    args = p.parse_args()

    family = _family_from_path(args.model_path)
    print(f'[streaming-needle] family={family} method={args.method} '
          f'k={args.k}', flush=True)
    model, tokenizer = load_backbone(args.model_path, args.multi_gpu)
    inject_layers = _inject_layers(model.config.num_hidden_layers)

    import torch
    from transformers import DynamicCache
    from baselines.eval_needle import generate_haystack, NEEDLES

    cfg = model.config
    nl = cfg.num_hidden_layers
    nq = cfg.num_attention_heads
    nkv = cfg.num_key_value_heads
    hd = getattr(cfg, 'head_dim', cfg.hidden_size // nq)
    embed_dev = model.get_input_embeddings().weight.device

    all_results = {}
    for n_win in args.n_windows_list:
        key = f'n{n_win}'
        depths = depth_positions(n_win)
        all_results[key] = {dk: 0 for dk in DEPTH_KEYS}
        for di, depth in enumerate(depths):
            dk = DEPTH_KEYS[di]; hits = 0; t0 = time.time()
            for trial in range(args.n_trials):
                seed = trial + args.seed_offset
                needle_idx = seed % len(NEEDLES)
                windows, question, answer = generate_haystack(
                    n_win, depth, needle_idx=needle_idx, seed=seed)
                # 1) AstroNet S1 protocol: process each window FRESH
                #    (no past_key_values), then concat per-window K/V
                #    along the seq dim. Required for RoPE position
                #    alignment with question Q during scoring.
                per_K = {li: [] for li in range(nl)}
                per_V = {li: [] for li in range(nl)}
                last_w_size = 0
                for win in windows:
                    ids = tokenizer(win, return_tensors='pt',
                                     truncation=True,
                                     max_length=512).to(embed_dev)
                    out = model(input_ids=ids['input_ids'], use_cache=True)
                    pkv = out.past_key_values
                    last_w_size = ids['input_ids'].shape[1]
                    for li in range(nl):
                        per_K[li].append(pkv.key_cache[li])
                        per_V[li].append(pkv.value_cache[li])
                all_kv = []
                for li in range(nl):
                    K = torch.cat(per_K[li], dim=2)
                    V = torch.cat(per_V[li], dim=2)
                    all_kv.append((K, V))
                total_len = all_kv[0][0].shape[-2]

                # 2) Question Q.
                q_text = f'Question: {question}\nAnswer:'
                q_states = _question_q_at_layers(
                    model, tokenizer, q_text, inject_layers, embed_dev)

                # 3) Score + select (uniform budget across layers).
                if args.method == 'snapkv':
                    cross = _score_method(all_kv, q_states, inject_layers, nq,
                                            nkv, hd, total_len, 'snapkv', 7,
                                            'maxpool')
                elif args.method == 'h2o':
                    cross = _score_method(all_kv, q_states, inject_layers, nq,
                                            nkv, hd, total_len, 'h2o', 1,
                                            'avgpool')
                else:
                    cross = _score_method(all_kv, q_states, inject_layers, nq,
                                            nkv, hd, total_len, 'pyramidkv', 5,
                                            'maxpool')
                sel = _select_indices(cross, total_len, args.k, args.method,
                                        last_w_size, nl, beta=20)

                # 4) Fresh cache + greedy decode.
                new_cache = DynamicCache()
                for li in range(nl):
                    K, V = _select_kv(all_kv, li, sel)
                    new_cache.update(K, V, li)
                prefix_len = sel.shape[0]
                qp = (f'Based on what you read earlier, answer the following '
                       f'question.\nQuestion: {question}\nAnswer:')
                qids = tokenizer(qp, return_tensors='pt',
                                  truncation=True, max_length=384).to(embed_dev)
                pos = torch.arange(prefix_len,
                                     prefix_len + qids['input_ids'].shape[1],
                                     device=embed_dev).unsqueeze(0)
                cur = qids['input_ids']; gen = []
                for _ in range(32):
                    out = model(input_ids=cur, past_key_values=new_cache,
                                  position_ids=pos, use_cache=True)
                    new_cache = out.past_key_values
                    nxt = out.logits[0, -1].argmax().unsqueeze(0).unsqueeze(0)
                    tok_id = int(nxt[0, 0].item())
                    gen.append(tok_id)
                    if tok_id == tokenizer.eos_token_id: break
                    cur = nxt.to(embed_dev)
                    pos = torch.tensor(
                        [[prefix_len + qids['input_ids'].shape[1] + len(gen) - 1]],
                        device=embed_dev)
                ans_text = tokenizer.decode(
                    gen, skip_special_tokens=True).strip()
                if answer.lower() in ans_text.lower():
                    hits += 1
            all_results[key][dk] = hits / args.n_trials
            print(f'  n={n_win} depth={dk}: {hits}/{args.n_trials} '
                   f'({hits/args.n_trials*100:.0f}%)  '
                   f'({time.time() - t0:.0f}s)', flush=True)
    averages = {key: sum(all_results[key].values()) / len(DEPTH_KEYS)
                 for key in all_results}
    os.makedirs(os.path.dirname(args.save_path) or '.', exist_ok=True)
    with open(args.save_path, 'w') as f:
        json.dump({
            'model': os.path.basename(args.model_path),
            'family': family, 'method': args.method, 'k': args.k,
            'n_trials': args.n_trials, 'seed_offset': args.seed_offset,
            'results': all_results, 'average_per_n': averages,
            'source': 'streaming-mode Needle (cumulative KV, '
                       'question-conditioned scoring, AstroNet S1 protocol)',
        }, f, indent=2)
    print(f'\nSaved -> {args.save_path}', flush=True)


if __name__ == '__main__':
    main()
